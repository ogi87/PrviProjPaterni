    public InputComboBoxPanel(String label) {
        this();
        setLabel(label);
        if (label != null) {
            String clean = label.replace(":", "").trim().toLowerCase();
            if (clean.equals("pol") || clean.equals("gender")) {
                setItems(new String[]{"--- Odaberi pol ---", "Muski", "Zenski"});
            } else if (clean.contains("bračni") || clean.contains("bracni") || clean.contains("marital")) {
                setItems(new String[]{
                    "--- Odaberite bracni status ---",
                    "Neozenjen / Neudata",
                    "Ozenjen / Udata",
                    "Razveden / Razvedena"
                });
            }
        }
    }

    public InputComboBoxPanel(String label, Object[] items) {
        this();
        setLabel(label);
        setItems(items);
    }

    public InputComboBoxPanel(String label, java.util.List<?> items) {
        this();
        setLabel(label);
        setItems(items);
    }

    @Override
    public void setLabel(String label) {
        if (staticText != null) {
            staticText.setText(label);
        }
    }

    @Override
    public String getLabel() {
        return staticText != null ? staticText.getText() : "";
    }

    public void setItems(Object[] items) {
        cbInput.removeAllItems();
        if (items != null) {
            for (Object item : items) {
                cbInput.addItem(item);
            }
        }
    }

    public void setItems(java.util.List<?> items) {
        cbInput.removeAllItems();
        if (items != null) {
            for (Object item : items) {
                cbInput.addItem(item);
            }
        }
    }

    public void setValue(Object value) {
        cbInput.setSelectedItem(value);
        clearError();
    }

    public JLabel getStaticText() {
        return staticText;
    }

    public JComboBox<Object> getCbInput() {
        return cbInput;
    }

    public JLabel getErrorText() {
        return errorText;
    }

    @Override
    public void clearError() {
        errorText.setText("");
    }

    @Override
    public void reset() {
        if (cbInput.getItemCount() > 0) {
            cbInput.setSelectedIndex(0);
        }
        clearError();
    }

    @Override
    public Object getValue() throws Exception {
        clearError();
        Object selected = cbInput.getSelectedItem();
        int selectedIndex = cbInput.getSelectedIndex();

        if (selected == null || selectedIndex < 0 || selected.toString().trim().isEmpty() || selected.toString().startsWith("---")) {
            String label = getLabel().replace(":", "").trim();
            if (label.isEmpty()) {
                label = "vrednost";
            }
            String errorMsg = "Morate odabrati " + label;
            errorText.setText(errorMsg);
            throw new Exception(errorMsg);
        }

        return selected.toString();
    }

