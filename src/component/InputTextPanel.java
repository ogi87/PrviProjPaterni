    public InputTextPanel(String label) {
        this();
        setLabel(label);
        if (label != null) {
            String clean = label.replace(":", "").trim().toLowerCase();
            if (clean.equals("pol") || clean.equals("gender")) {
                this.myValidator = new validator.GenderValidator();
            } else if (clean.contains("bračni") || clean.contains("bracni") || clean.contains("marital")) {
                this.myValidator = new validator.MaritalStatusValidator();
            }
        }
    }

    public InputTextPanel(String label, MyValidator myValidator) {
        this(label);
        this.myValidator = myValidator;
    }

    @Override
    public void setLabel(String label) {
        if (staticText != null) {
            staticText.setText(label);
        }
    }

    @Override
    public String getLabel() {
        return staticText != null ? staticText.getText() : "";
    }

    public JTextField getInputText() {
        return inputText;
    }

    public JLabel getStaticText() {
        return staticText;
    }

    public JLabel getErrorText() {
        return errorText;
    }

    @Override
    public void clearError() {
        errorText.setText("");
    }

    @Override
    public void reset() {
        inputText.setText("");
        clearError();
    }

    public void setValue(String value) {
        inputText.setText(value == null ? "" : value);
        clearError();
    }

    @Override
    public Object getValue() throws Exception {
        clearError();
        String text = inputText.getText().trim();

        if (text.isEmpty()) {
            errorText.setText("Polje ne sme biti prazno");
            throw new Exception("Polje ne sme biti prazno");
        }

        if (myValidator != null) {
            try {
                myValidator.validate(text);
            } catch (Exception e) {
                errorText.setText(e.getMessage());
                throw e;
            }
        }

        return text;
    }

