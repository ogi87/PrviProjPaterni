    @Override
    public void clearError() {
        errorText.setText("");
    }

    @Override
    public void reset() {
        inputText.setText("");
        clearError();
    }

    public void setValue(LocalDate date) {
        if (date != null) {
            inputText.setText(date.format(DateTimeFormatter.ofPattern("dd.MM.yyyy")));
        } else {
            inputText.setText("");
        }
        clearError();
    }

    public void setValue(String dateText) {
        inputText.setText(dateText == null ? "" : dateText);
        clearError();
    }

    @Override
    public Object getValue() throws Exception {
        clearError();
        String text = inputText.getText().trim();

        if (text.isEmpty()) {
            errorText.setText("Datum rodjenja je obavezan");
            throw new Exception("Polje 'Datum rodjenja' je obavezno");
        }

        if (myValidator != null) {
            try {
                myValidator.validate(text);
            } catch (Exception e) {
                errorText.setText(e.getMessage());
                throw e;
            }
        }

        if (text.endsWith(".")) {
            text = text.substring(0, text.length() - 1).trim();
        }

        return LocalDate.parse(text, DateTimeFormatter.ofPattern("dd.MM.uuuu"));
    }

