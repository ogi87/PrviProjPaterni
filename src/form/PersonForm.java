    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        boolean hasError = false;
        StringBuilder errorMessages = new StringBuilder();

        // 1. Ime
        String fN = null;
        try {
            fN = firstName.getValue().toString();
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        // 2. Prezime
        String lN = null;
        try {
            lN = lastName.getValue().toString();
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        // 3. Godine
        Integer ageNumber = null;
        try {
            ageNumber = Integer.parseInt(age.getValue().toString());
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        // 4. Pol
        String genderValue = null;
        try {
            genderValue = gender.getValue().toString();
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        // 5. Datum rodjenja
        LocalDate dateValue = null;
        try {
            dateValue = (LocalDate) dateOfBirth.getValue();
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        // 6. Bracni status
        String maritalStatusValue = null;
        try {
            maritalStatusValue = maritalStatus.getValue().toString();
        } catch (Exception ex) {
            hasError = true;
            errorMessages.append("• ").append(ex.getMessage()).append("\n");
        }

        if (hasError) {
            JOptionPane.showMessageDialog(this,
                    "Molimo ispravite sledece greske pre cuvanja:\n\n" + errorMessages.toString(),
                    "Greska pri validaciji unosa",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        Person person = new Person(fN, lN, ageNumber, genderValue, dateValue, maritalStatusValue);

        JOptionPane.showMessageDialog(this,
                "Podaci o osobi su uspesno sacuvani!\n\n" + person.toString(),
                "Uspesno sacuvano",
                JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnSaveActionPerformed

